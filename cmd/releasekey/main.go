// Command releasekey manages the Ed25519 key that signs release checksums.
//
//	go run ./cmd/releasekey gen                 # new key pair (one time)
//	go run ./cmd/releasekey sign checksums.txt   # CI: needs UPDATE_SIGNING_KEY env
//	go run ./cmd/releasekey verify checksums.txt # checks .sig with release-key.pub
package main

import (
	"crypto/ed25519"
	"crypto/rand"
	"encoding/base64"
	"fmt"
	"os"
	"strings"

	"github.com/phpandrew/TSG-Embroidery-Pro/internal/updater"
)

const pubPath = "internal/updater/release-key.pub"

func die(format string, a ...any) {
	fmt.Fprintf(os.Stderr, format+"\n", a...)
	os.Exit(1)
}

func main() {
	if len(os.Args) < 2 {
		die("usage: releasekey gen | sign <file> | verify <file>")
	}
	switch os.Args[1] {
	case "gen":
		pub, priv, err := ed25519.GenerateKey(rand.Reader)
		if err != nil {
			die("%v", err)
		}
		content := "# Ed25519 public key that verifies release checksums.\n" +
			"# Generated by: go run ./cmd/releasekey gen\n" +
			base64.StdEncoding.EncodeToString(pub) + "\n"
		if err := os.WriteFile(pubPath, []byte(content), 0o644); err != nil {
			die("write %s: %v (run from the repo root)", pubPath, err)
		}
		secret := base64.StdEncoding.EncodeToString(priv.Seed())
		if err := os.WriteFile("release-signing-key.txt", []byte(secret+"\n"), 0o600); err != nil {
			die("%v", err)
		}
		fmt.Println("Public key written to", pubPath, "- commit it.")
		fmt.Println("Private key written to release-signing-key.txt (git-ignored).")
		fmt.Println("1. Add it as the GitHub Actions secret UPDATE_SIGNING_KEY:")
		fmt.Println("     gh secret set UPDATE_SIGNING_KEY < release-signing-key.txt")
		fmt.Println("2. Store a backup in your password manager, then delete the file.")
	case "sign":
		if len(os.Args) < 3 {
			die("usage: releasekey sign <file>")
		}
		seed, err := base64.StdEncoding.DecodeString(strings.TrimSpace(os.Getenv("UPDATE_SIGNING_KEY")))
		if err != nil || len(seed) != ed25519.SeedSize {
			die("UPDATE_SIGNING_KEY missing or invalid")
		}
		priv := ed25519.NewKeyFromSeed(seed)
		data, err := os.ReadFile(os.Args[2])
		if err != nil {
			die("%v", err)
		}
		// refuse to sign with a key that doesn't match the committed public key
		if pub, err := updater.ParsePublicKey(mustRead(pubPath)); err == nil {
			if !pub.Equal(priv.Public()) {
				die("signing key does not match %s", pubPath)
			}
		} else {
			die("%s has no public key; run gen first", pubPath)
		}
		sig := base64.StdEncoding.EncodeToString(ed25519.Sign(priv, data))
		if err := os.WriteFile(os.Args[2]+".sig", []byte(sig+"\n"), 0o644); err != nil {
			die("%v", err)
		}
		fmt.Println("signed", os.Args[2])
	case "verify":
		if len(os.Args) < 3 {
			die("usage: releasekey verify <file>")
		}
		pub, err := updater.ParsePublicKey(mustRead(pubPath))
		if err != nil {
			die("%v", err)
		}
		data, _ := os.ReadFile(os.Args[2])
		sig, _ := os.ReadFile(os.Args[2] + ".sig")
		raw, err := base64.StdEncoding.DecodeString(strings.TrimSpace(string(sig)))
		if err != nil || !ed25519.Verify(pub, data, raw) {
			die("signature INVALID")
		}
		fmt.Println("signature OK")
	default:
		die("unknown command %q", os.Args[1])
	}
}

func mustRead(p string) string {
	b, err := os.ReadFile(p)
	if err != nil {
		return ""
	}
	return string(b)
}
